"""Curation snapshot — an exact, reproducible record of what each tag contributed, and how it changed.

The engine's per-tag applied files (``{per_sample,backfill,escalation}_applied_<tag>.tsv``) are the inputs
``engine.cli.accumulate`` replays onto the raw base to build the master. They are therefore the ground truth
for "what did we have". This script counts them — per **tag × source × field** — plus each tag's graded-study
count and how many studies were graded from a hand-downloaded PDF.

Its point is the **baseline comparison**: pass ``--baseline-ref <git-ref>`` and the same counts are read from
that commit (via ``git show``), giving an exact before → after delta without hand-copying numbers. This is the
durable record that makes a deliberate change (e.g. re-freezing the byte-for-byte reference outputs after an
intended extractor change) reviewable rather than silent.

Deterministic, read-only, no LLM. Writes ``diagnostics/curation_snapshot.{md,tsv}``.
"""

from __future__ import annotations

import argparse
import io
import subprocess
import sys
from pathlib import Path

import pandas as pd

from bac_metadata.bac_agentic_metadata.engine import backfill
from bac_metadata.bac_agentic_metadata.engine.run_layout import RunPaths

ENGINE_APPS = Path(__file__).resolve().parents[1] / "applications"
DEFAULT_TAGS = ("train", "test", "tail100", "tail50_99", "tail25_49", "tail10_24", "sub10")


def _repo_root() -> Path:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True)
    return Path(out.stdout.strip())


def _read(path: Path, ref: str | None, root: Path) -> pd.DataFrame:
    """Read a TSV from the working tree, or from ``ref`` via ``git show``; empty frame if absent."""
    if ref is None:
        if not path.exists():
            return pd.DataFrame()
        return pd.read_csv(path, sep="\t", dtype=str, keep_default_na=False)
    rel = path.relative_to(root)
    proc = subprocess.run(["git", "show", f"{ref}:{rel}"], capture_output=True, cwd=root)
    if proc.returncode != 0 or not proc.stdout.strip():
        return pd.DataFrame()
    return pd.read_csv(io.BytesIO(proc.stdout), sep="\t", dtype=str, keep_default_na=False)


def snapshot(data_dir: Path, tags: list[str], ref: str | None, root: Path) -> pd.DataFrame:
    """Per (tag, source, field) non-blank fill counts, plus per-tag study/paper counts as pseudo-rows."""
    rows = []
    for tag in tags:
        rp = RunPaths(data_dir, tag)
        sources = {"per_sample": rp.per_sample_applied, "whole_field": rp.backfill_applied,
                   "escalation": rp.escalation_applied}
        for source, path in sources.items():
            df = _read(path, ref, root)
            if len(df) and {"field", "applied_value"} <= set(df.columns):
                real = df[backfill.strip_placeholders(df["applied_value"]).notna()]
                for field, g in real.groupby("field"):
                    rows.append({"tag": tag, "source": source, "field": field, "fills": len(g)})
        g = _read(rp.study_grades_tsv, ref, root)
        n_studies = len(g)
        n_local = int((g["fulltext_source"] == "local_pdf").sum()) if "fulltext_source" in g.columns else 0
        rows.append({"tag": tag, "source": "_meta", "field": "graded_studies", "fills": n_studies})
        rows.append({"tag": tag, "source": "_meta", "field": "graded_from_manual_pdf", "fills": n_local})
    return pd.DataFrame(rows, columns=["tag", "source", "field", "fills"])


def _pivot_fills(snap: pd.DataFrame) -> pd.DataFrame:
    f = snap[snap["source"] != "_meta"]
    if f.empty:
        return pd.DataFrame()
    return f.pivot_table(index=["tag", "source"], columns="field", values="fills", aggfunc="sum",
                         fill_value=0).reset_index()


def _render_md(now: pd.DataFrame, before: pd.DataFrame | None, ref: str | None) -> str:
    lines = ["# Curation snapshot — per-tag applied fills", "",
             "Auto-generated by `evaluation/curation_snapshot.py` (read-only, no LLM). These per-tag applied "
             "files are exactly what `engine.cli.accumulate` replays onto the raw base to build the master, so "
             "they are the authoritative record of what each tag contributed.", ""]

    tot_now = int(now[now["source"] != "_meta"]["fills"].sum())
    if before is not None:
        tot_b = int(before[before["source"] != "_meta"]["fills"].sum())
        lines += [f"**Total curated cells: {tot_b:,} → {tot_now:,} ({tot_now - tot_b:+,})** vs baseline `{ref}`.", ""]
    else:
        lines += [f"**Total curated cells: {tot_now:,}.**", ""]

    # per tag x source totals, with delta
    def _agg(df):
        return df[df["source"] != "_meta"].groupby(["tag", "source"])["fills"].sum()

    a = _agg(now)
    lines += ["## Fills by tag × source", "",
              "| tag | source | fills" + (" | baseline | delta |" if before is not None else " |"),
              "|---|---|--:" + ("|--:|--:|" if before is not None else "|")]
    b = _agg(before) if before is not None else None
    for (tag, source), v in a.items():
        if before is not None:
            bv = int(b.get((tag, source), 0))
            lines.append(f"| {tag} | {source} | {int(v):,} | {bv:,} | {int(v) - bv:+,} |")
        else:
            lines.append(f"| {tag} | {source} | {int(v):,} |")
    lines.append("")

    # meta: graded studies + manual-PDF grades
    m = now[now["source"] == "_meta"].pivot_table(index="tag", columns="field", values="fills",
                                                  aggfunc="sum", fill_value=0)
    lines += ["## Graded studies / papers consumed", "",
              "| tag | graded studies | graded from manual PDF |", "|---|--:|--:|"]
    for tag, r in m.iterrows():
        lines.append(f"| {tag} | {int(r.get('graded_studies', 0))} | {int(r.get('graded_from_manual_pdf', 0))} |")
    lines.append("")

    piv = _pivot_fills(now)
    if len(piv):
        fields = [c for c in piv.columns if c not in ("tag", "source")]
        lines += ["## Fills by field", "", "| tag | source | " + " | ".join(fields) + " |",
                  "|---|---|" + "--:|" * len(fields)]
        for _, r in piv.iterrows():
            lines.append(f"| {r['tag']} | {r['source']} | " + " | ".join(f"{int(r[f]):,}" for f in fields) + " |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    """Write the curation snapshot, optionally as a before → after delta against a git ref."""
    p = argparse.ArgumentParser(description="Per-tag applied-fill snapshot, with optional git baseline delta.")
    p.add_argument("--app", default="klebsiella", help="Application under applications/ (default klebsiella).")
    p.add_argument("--tags", default=",".join(DEFAULT_TAGS), help="Comma-separated tags.")
    p.add_argument("--baseline-ref", default=None, help="Git ref to compare against (e.g. 258aba1).")
    p.add_argument("--out-prefix", default="curation_snapshot", help="Basename under diagnostics/.")
    args = p.parse_args()

    root = _repo_root()
    data_dir = ENGINE_APPS / args.app / "data"
    tags = [t.strip() for t in args.tags.split(",") if t.strip()]

    now = snapshot(data_dir, tags, None, root)
    before = snapshot(data_dir, tags, args.baseline_ref, root) if args.baseline_ref else None

    diagnostics = data_dir / "diagnostics"
    diagnostics.mkdir(parents=True, exist_ok=True)
    (diagnostics / f"{args.out_prefix}.md").write_text(_render_md(now, before, args.baseline_ref))
    out = now.copy()
    if before is not None:
        out = now.merge(before, on=["tag", "source", "field"], how="outer", suffixes=("", "_baseline")).fillna(0)
        out["delta"] = out["fills"] - out["fills_baseline"]
    out.to_csv(diagnostics / f"{args.out_prefix}.tsv", sep="\t", index=False)

    tot = int(now[now["source"] != "_meta"]["fills"].sum())
    print(f"Wrote diagnostics/{args.out_prefix}.{{md,tsv}} — {tot:,} curated cells across {len(tags)} tags",
          file=sys.stderr)
    if before is not None:
        tb = int(before[before["source"] != "_meta"]["fills"].sum())
        print(f"baseline {args.baseline_ref}: {tb:,} → {tot:,} ({tot - tb:+,})", file=sys.stderr)


if __name__ == "__main__":
    main()
